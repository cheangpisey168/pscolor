export function getAccessibleMutedTextColor(bgHex) {
  if (!bgHex || !/^#[0-9a-f]{6}$/i.test(bgHex)) return '#475569';
  const lum = getLuminance(bgHex);
  if (lum > 0.4) {
    return getContrast(bgHex, '#475569') >= 4.5 ? '#475569' : '#1e293b';
  } else {
    return getContrast(bgHex, '#cbd5e1') >= 4.5 ? '#cbd5e1' : '#f8fafc';
  }
}

export function getAccessibleBorderColor(bgHex) {
  if (!bgHex || !/^#[0-9a-f]{6}$/i.test(bgHex)) return 'rgba(15, 23, 42, 0.12)';
  const lum = getLuminance(bgHex);
  return lum > 0.4 ? 'rgba(15, 23, 42, 0.12)' : 'rgba(255, 255, 255, 0.16)';
}

export function getAccessibleSubtleBg(bgHex) {
  if (!bgHex || !/^#[0-9a-f]{6}$/i.test(bgHex)) return 'rgba(0, 0, 0, 0.04)';
  const lum = getLuminance(bgHex);
  return lum > 0.4 ? 'rgba(15, 23, 42, 0.05)' : 'rgba(255, 255, 255, 0.08)';
}

