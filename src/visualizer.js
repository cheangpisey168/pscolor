export function getReadableTextColor(bgHex) {
  if (!bgHex || !/^#[0-9a-f]{6}$/i.test(bgHex)) return '#0f172a';
  const darkContrast = getContrast(bgHex, '#0f172a');
  const lightContrast = getContrast(bgHex, '#ffffff');
  return darkContrast >= lightContrast ? '#0f172a' : '#ffffff';
}

export function getDefaultRoles(colors) {
  const c = colors || ['#F7F0DC', '#D9E4C8', '#A2B89B', '#52796F'];
  const bg = c[0];
  const surface = c[1] || c[0];
  const secondary = c[2] || c[1];
  const primary = c[3] || c[2];
  const accent = c[3] || c[2];
  const text = getReadableTextColor(bg);

  return {
    background: bg,
    surface: surface,
    secondary: secondary,
    primary: primary,
    accent: accent,
    text: text
  };
}

