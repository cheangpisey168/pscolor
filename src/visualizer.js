  attachListeners() {
    this.updateView();
    this.updateRoleSelectors();
    this.updateContrastScorecard();
    this.updateViewportClass();

    // Template switcher tabs
    document.querySelectorAll('.visualizer-template-tab').forEach(btn => {
      btn.addEventListener('click', () => {
        this.setTemplate(btn.dataset.template);
      });
    });

    // Viewport switcher
    const desktopBtn = document.querySelector('#btn-view-desktop');
    const mobileBtn = document.querySelector('#btn-view-mobile');
    if (desktopBtn) desktopBtn.addEventListener('click', () => this.setViewport('desktop'));
    if (mobileBtn) mobileBtn.addEventListener('click', () => this.setViewport('mobile'));

    // Try another palette
    const tryAnotherBtn = document.querySelector('#btn-try-another');
    if (tryAnotherBtn) {
      tryAnotherBtn.addEventListener('click', () => {
        const randomIndex = Math.floor(Math.random() * palettes.length);
        const randomPalette = palettes[randomIndex];
        this.setPalette(randomPalette);
      });
    }

    // Role quick modifiers
    const shuffleBtn = document.querySelector('#btn-shuffle-roles');
    if (shuffleBtn) shuffleBtn.addEventListener('click', () => this.shuffleRoles());

    const invertBtn = document.querySelector('#btn-invert-theme');
    if (invertBtn) invertBtn.addEventListener('click', () => this.invertTheme());

    const resetBtn = document.querySelector('#btn-reset-roles');
    if (resetBtn) resetBtn.addEventListener('click', () => this.resetRoles());

    // Role swatch delegation
    const roleContainer = document.querySelector('#visualizer-role-selectors');
    if (roleContainer) {
      roleContainer.addEventListener('click', e => {
        const btn = e.target.closest('.role-swatch-btn');
        if (!btn) return;
        const role = btn.dataset.role;
        const color = btn.dataset.color;
        if (role) {
          const finalColor = color === 'auto' ? getReadableTextColor(this.roles.background) : color;
          this.updateRole(role, finalColor);
          this.updateRoleSelectors();
        }
      });
    }

    // Export CSS & Tailwind
    const cssBtn = document.querySelector('#btn-export-css');
    if (cssBtn) {
      cssBtn.addEventListener('click', async () => {
        const snippet = generateRoleCssSnippet(this.roles, this.colors);
        const res = await copyTextToClipboard(snippet);
        if (res.success) {
          window.dispatchEvent(new CustomEvent('ps-color-toast', { detail: 'Copied UI CSS variables to clipboard' }));
          trackUiPreviewExport('css', this.palette?.id);
        } else {
          window.dispatchEvent(new CustomEvent('ps-color-toast', { detail: 'Unable to write to clipboard. Please check clipboard permissions or copy manually.' }));
        }
      });
    }

    const tailwindBtn = document.querySelector('#btn-export-tailwind');
    if (tailwindBtn) {
      tailwindBtn.addEventListener('click', async () => {
        const snippet = generateRoleTailwindSnippet(this.roles);
        const res = await copyTextToClipboard(snippet);
        if (res.success) {
          window.dispatchEvent(new CustomEvent('ps-color-toast', { detail: 'Copied UI Tailwind configuration' }));
          trackUiPreviewExport('tailwind', this.palette?.id);
        } else {
          window.dispatchEvent(new CustomEvent('ps-color-toast', { detail: 'Unable to write to clipboard. Please check clipboard permissions or copy manually.' }));
        }
      });
    }

    const figmaBtn = document.querySelector('#btn-export-figma');
    if (figmaBtn) {
      figmaBtn.addEventListener('click', async () => {
        const snippet = generateRoleFigmaSnippet(this.roles);
        const res = await copyTextToClipboard(snippet);
        if (res.success) {
          window.dispatchEvent(new CustomEvent('ps-color-toast', { detail: 'Copied UI Figma tokens JSON' }));
          trackUiPreviewExport('figma', this.palette?.id);
        } else {
          window.dispatchEvent(new CustomEvent('ps-color-toast', { detail: 'Unable to write to clipboard. Please check clipboard permissions or copy manually.' }));
        }
      });
    }

    const shareImgBtn = document.querySelector('#btn-visualizer-share-image');
    if (shareImgBtn) {
      shareImgBtn.addEventListener('click', () => {
        openShareImageModal(this.palette, {
          colors: this.colors,
          title: 'PS Color Visualizer Theme'
        });
      });
    }
  }
